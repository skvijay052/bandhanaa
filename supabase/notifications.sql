insert into public.notifications (user_id, actor_id, type, title, subtitle, href, source_key, created_at)
select
  liker_id,
  liked_id,
  'accepted',
  'accepted your interest.',
  'You can start a conversation now.',
  '/messages',
  'accepted:' || liker_id::text || ':' || liked_id::text,
  coalesce(responded_at, created_at)
from public.profile_likes
where status = 'accepted'
on conflict (source_key) do nothing;

insert into public.notifications (user_id, actor_id, type, title, subtitle, href, source_key, read_at, created_at)
select
  case when sender_id = interest_liker_id then interest_liked_id else interest_liker_id end,
  sender_id,
  'message',
  'sent you a message.',
  left(body, 160),
  '/messages',
  'message:' || id::text,
  read_at,
  created_at
from public.messages
on conflict (source_key) do nothing;

